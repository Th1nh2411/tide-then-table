"""Stage pending brief-5 concepts for the existing Windows local CPU tool.

No inference/network calls. Run from any working directory:
    python tools/art/stage_horror_brief5.py
Then run the generated run_pending.ps1 on Windows. Existing verified outputs
are skipped; each failed asset gets one isolated retry after its group.
"""
import hashlib
import json
from datetime import datetime
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = Path(__file__).with_name('horror_brief5_models.json')


def complete(name: str) -> bool:
    out = ROOT/'assets/models/ready'/name
    record_path = out/'hunyuan_provenance.json'
    if not record_path.is_file():
        return False
    try:
        record = json.loads(record_path.read_text())
        if record.get('status') != 'success':
            return False
        for kind in ['raw', 'reduced']:
            path = out/f'{name}_{kind}.glb'
            if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != record.get(kind+'_sha256'):
                return False
        source = ROOT/f'assets/concepts/horror/{name}.png'
        return hashlib.sha256(source.read_bytes()).hexdigest() == record.get('input_sha256')
    except (ValueError, OSError):
        return False


def main() -> None:
    groups = json.loads(MANIFEST.read_text())
    names = [n for group in groups.values() for n in group]
    assert len(names) == len(set(names)) == 25
    stage = ROOT/'build/hunyuan_brief5'/datetime.now().strftime('%Y%m%d_%H%M%S_%f')
    stage.mkdir(parents=True)
    pending = {budget: [n for n in group if not complete(n)] for budget, group in groups.items()}
    (stage/'pending.json').write_text(json.dumps(pending, indent=2)+'\n')
    script = [
        '# Generated by tools/art/stage_horror_brief5.py; local/offline only.',
        "$ErrorActionPreference = 'Stop'",
        '$root = (Resolve-Path (Join-Path $PSScriptRoot "../../..")).Path',
        'Set-Location $root',
        'function Test-Ready([string]$id) {',
        '    $out = Join-Path $root "assets/models/ready/$id"',
        '    $p = Join-Path $out "hunyuan_provenance.json"',
        '    if (-not (Test-Path $p)) { return $false }',
        '    try {',
        '        $r = Get-Content -Raw $p | ConvertFrom-Json',
        '        if ($r.status -ne "success") { return $false }',
        '        foreach ($kind in @("raw", "reduced")) {',
        '            $file = Join-Path $out "${id}_${kind}.glb"',
        '            if (-not (Test-Path $file)) { return $false }',
        '            if ((Get-FileHash $file -Algorithm SHA256).Hash.ToLower() -ne $r."${kind}_sha256") { return $false }',
        '        }',
        '        return (Get-FileHash "assets/concepts/horror/$id.png" -Algorithm SHA256).Hash.ToLower() -eq $r.input_sha256',
        '    } catch { return $false }',
        '}',
    ]
    remaining = []
    for budget, group in pending.items():
        if not group:
            continue
        folder = stage/budget
        folder.mkdir()
        for name in group:
            source = ROOT/f'assets/concepts/horror/{name}.png'
            shutil.copy2(source, folder/source.name)
        relative = folder.relative_to(ROOT).as_posix()
        # The existing local CLI uses a different output convention for a
        # one-image folder; pass an explicit per-ID directory in that case.
        if len(group) > 1:
            script.append(f'& powershell -NoProfile -File tools/art/hunyuan_local.ps1 -InputDir "{relative}" -OutDir assets/models/ready -Faces {budget}')
        else:
            name = group[0]
            script.append(f'& powershell -NoProfile -File tools/art/hunyuan_local.ps1 -Image "{relative}/{name}.png" -Name {name} -OutDir "assets/models/ready/{name}" -Faces {budget}')
        script.append('foreach ($id in @('+', '.join('"'+n+'"' for n in group)+')) {')
        script.append('    if (-not (Test-Ready $id)) {')
        script.append(f'        & powershell -NoProfile -File tools/art/hunyuan_local.ps1 -Image "assets/concepts/horror/$id.png" -Name $id -OutDir "assets/models/ready/$id" -Faces {budget}')
        script.extend(['    }', '}'])
        remaining.extend(group)
    script.append('$failed = @()')
    for name in remaining:
        script.append(f'if (-not (Test-Ready "{name}")) {{ $failed += "{name}" }}')
    script.extend(['if ($failed.Count) { Write-Host "REMAINING:" ($failed -join ", "); exit 1 }', 'Write-Host "LOCAL BATCH OK; mesh/material validation and three-view review still required."'])
    (stage/'run_pending.ps1').write_text('\n'.join(script)+'\n', encoding='utf-8-sig')
    print(json.dumps(pending, indent=2))
    print('Staged',len(remaining),'pending concepts at',stage.relative_to(ROOT))
    print('Windows: powershell -NoProfile -File', (stage/'run_pending.ps1').relative_to(ROOT))


if __name__ == '__main__':
    main()
